/// The enterprise `policies.json` that installs Shrike's CA (so HTTPS is trusted
/// with no prompts) and quiets first-run/update noise. `ca_path` is an absolute
/// path to the CA PEM written alongside it.
pub fn firefox_policies_json(ca_path: &Path) -> String {
    let p = ca_path.to_string_lossy().replace('\\', "\\\\");
    format!(
        r#"{{
  "policies": {{
    "Certificates": {{ "ImportEnterpriseRoots": false, "Install": ["{p}"] }},
    "DisableTelemetry": true,
    "DisableFirefoxStudies": true,
    "DisableAppUpdate": true,
    "DontCheckDefaultBrowser": true,
    "OverrideFirstRunPage": "",
    "OverridePostUpdatePage": ""
  }}
}}"#
    )
}

/// Write the Firefox profile (`user.js`) and best-effort install the CA policy.
///
/// The policy lives in `<binary dir>/distribution/policies.json`, which the
/// bundled Firefox (in a writable location) always accepts. A read-only system
/// Firefox may reject it; the proxy and home page still work from the profile,
/// and HTTPS warns until a bundled Firefox is used.
fn setup_firefox(cfg: &BrowserConfig) -> Result<()> {
    std::fs::create_dir_all(&cfg.profile_dir)
        .with_context(|| format!("creating browser profile {}", cfg.profile_dir.display()))?;
    write_if_changed(
        &cfg.profile_dir.join("user.js"),
        firefox_user_js(cfg.listen, &cfg.start_url).as_bytes(),
    )
    .context("writing firefox user.js")?;

    // Trust Shrike's CA. Primary: install it into the profile's cert9.db with
    // certutil (writable, so it works even when the install dir is read-only, as
    // in a packaged build). Fallback below: the enterprise policy next to the
    // binary, which applies when that directory is writable (a dev run).
    install_ca_into_profile(cfg);

    if let Some(dir) = cfg.bin.parent() {
        let dist = dir.join("distribution");
        let ca_path = dist.join("shrike-ca.pem");
        let write = std::fs::create_dir_all(&dist)
            .and_then(|_| write_if_changed(&ca_path, cfg.ca_pem.as_bytes()))
            .and_then(|_| {
                write_if_changed(
                    &dist.join("policies.json"),
                    firefox_policies_json(&ca_path).as_bytes(),
                )
            });
        if let Err(e) = write {
            tracing::warn!(
                error = %e,
                dir = %dist.display(),
                "could not install the Firefox CA policy (read-only install?); HTTPS may warn until Firefox is bundled"
            );
        }
    }
    Ok(())
}

/// Nickname for Shrike's CA in the Firefox profile's NSS database.
const CA_NICKNAME: &str = "Shrike CA";

/// Install Shrike's CA into the integrated Firefox profile's `cert9.db` with
/// `certutil`. The profile lives in Shrike's data directory, which is always
/// writable, so this trusts the CA even for installed packages whose resources
/// (and thus the policy file) are read-only. No-op, with a hint, when `certutil`
/// (nss-tools) is not installed; the policy file then covers writable installs.
fn install_ca_into_profile(cfg: &BrowserConfig) {
    if !crate::ca::trust::certutil_available() {
        tracing::info!(
            "certutil (nss-tools) not found; the integrated Firefox trusts Shrike's CA via the \
             policy file on a writable install. Install nss-tools for automatic trust everywhere."
        );
        return;
    }
    let pem = cfg.profile_dir.join("shrike-ca.pem");
    if let Err(e) = write_if_changed(&pem, cfg.ca_pem.as_bytes()) {
        tracing::warn!(error = %e, "writing the CA for the Firefox profile failed");
        return;
    }
    let db = crate::ca::trust::NssDatabase {
        label: "integrated Firefox".into(),
        dir: cfg.profile_dir.clone(),
    };
    match crate::ca::trust::trust_in_nss(&db, &pem, CA_NICKNAME) {
        Ok(()) => tracing::info!("Shrike CA installed into the integrated Firefox profile"),
        Err(e) => tracing::warn!(error = %e, "installing the CA into the Firefox profile failed"),
    }
}

/// Write `content` only when it differs from what is on disk, so relaunching
/// does not rewrite (and touch the mtime of) unchanged policy/profile files.
fn write_if_changed(path: &Path, content: &[u8]) -> std::io::Result<()> {
    if std::fs::read(path).ok().as_deref() == Some(content) {
        return Ok(());
    }
    std::fs::write(path, content)
}

/// Firefox command-line arguments: an isolated, single instance opened at `start_url`.
pub fn firefox_args(cfg: &BrowserConfig) -> Vec<String> {
    vec![
        "-no-remote".into(),
        "-profile".into(),
        cfg.profile_dir.display().to_string(),
        cfg.start_url.clone(),
    ]
}

// --- Chromium (fallback) ---------------------------------------------------

/// The command-line flags that wire a Chromium instance to Shrike.
pub fn build_args(cfg: &BrowserConfig) -> Vec<String> {
    let mut args = vec![
        format!("--user-data-dir={}", cfg.profile_dir.display()),
        format!("--proxy-server=http://{}", cfg.listen),
        format!("--ignore-certificate-errors-spki-list={}", cfg.spki_b64),
        "--no-first-run".into(),
        "--no-default-browser-check".into(),
        "--disable-background-networking".into(),
        "--disable-sync".into(),
        "--disable-component-update".into(),
        "--disable-features=Translate,OptimizationHints".into(),
    ];
    if in_flatpak() {
        args.push("--no-sandbox".into());
    }
    args.push(cfg.start_url.clone());
    args
}

/// True when running inside a Flatpak sandbox (set by the runtime).
fn in_flatpak() -> bool {
    std::env::var_os("FLATPAK_ID").is_some() || std::path::Path::new("/.flatpak-info").exists()
}

/// Launch the integrated browser (non-blocking).
pub fn launch(cfg: &BrowserConfig) -> Result<Child> {
    let mut cmd = Command::new(&cfg.bin);
    match cfg.engine {
        Engine::Firefox => {
            setup_firefox(cfg)?;
            cmd.args(firefox_args(cfg));
        }
        Engine::Chromium => {
            std::fs::create_dir_all(&cfg.profile_dir).with_context(|| {
                format!("creating browser profile {}", cfg.profile_dir.display())
            })?;
            cmd.args(build_args(cfg));
        }
    }
    // Bundled/portable browser builds can fail to locate the system fontconfig
    // ("Cannot load default config file"), then render with poor fallback fonts.
    // Point them at the system config when present and not already configured.
    if std::env::var_os("FONTCONFIG_PATH").is_none() {
        let sys = std::path::Path::new("/etc/fonts");
        if sys.is_dir() {
            cmd.env("FONTCONFIG_PATH", sys);
        }
    }
    // Disable the GTK/ATK accessibility bridge, which otherwise spams the console
    // with harmless "text_caret_moved"/GObject-CRITICAL warnings under Firefox on
    // some Linux desktops. It is not needed for an isolated testing browser.
    cmd.env("NO_AT_BRIDGE", "1");
    cmd.env("GTK_A11Y", "none");
    cmd.spawn()
        .with_context(|| format!("launching {}", cfg.bin.display()))
}

/// Best-effort discovery of a system Firefox (the preferred engine).
pub fn find_system_firefox(override_path: Option<&str>) -> Option<PathBuf> {
    if let Some(p) = override_path.filter(|s| !s.is_empty()) {
        let pb = PathBuf::from(p);
        if pb.is_file() && detect_engine(&pb) == Engine::Firefox {
            return Some(pb);
        }
    }
    const ABSOLUTE: &[&str] = &[
        "/usr/bin/firefox",
        "/usr/bin/firefox-esr",
        "/usr/lib/firefox/firefox",
        "/usr/lib64/firefox/firefox",
        "/snap/bin/firefox",
        "/var/lib/flatpak/exports/bin/org.mozilla.firefox",
        "/Applications/Firefox.app/Contents/MacOS/firefox",
        "C:\\Program Files\\Mozilla Firefox\\firefox.exe",
        "C:\\Program Files (x86)\\Mozilla Firefox\\firefox.exe",
    ];
    for a in ABSOLUTE {
        let pb = PathBuf::from(a);
        if pb.is_file() {
            return Some(pb);
        }
    }
    find_on_path(&["firefox", "firefox-esr", "librewolf"])
}

/// Best-effort discovery of a system Chromium-family browser (fallback only).
/// Honours `override_path` first, then well-known absolute locations, then `PATH`.
pub fn find_system_chromium(override_path: Option<&str>) -> Option<PathBuf> {
    if let Some(p) = override_path.filter(|s| !s.is_empty()) {
        let pb = PathBuf::from(p);
        if pb.is_file() && detect_engine(&pb) == Engine::Chromium {
            return Some(pb);
        }
    }

    const ABSOLUTE: &[&str] = &[
        "/usr/bin/chromium",
        "/usr/bin/chromium-browser",
        "/usr/bin/google-chrome",
        "/usr/bin/google-chrome-stable",
        "/usr/bin/brave-browser",
        "/usr/bin/microsoft-edge",
        "/snap/bin/chromium",
        "/snap/bin/google-chrome",
        "/var/lib/flatpak/exports/bin/org.chromium.Chromium",
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
        "/Applications/Chromium.app/Contents/MacOS/Chromium",
        "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser",
        "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
        "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe",
        "C:\\Program Files (x86)\\Google\\Chrome\\Application\\chrome.exe",
        "C:\\Program Files\\Microsoft\\Edge\\Application\\msedge.exe",
        "C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe",
    ];
    for a in ABSOLUTE {
        let pb = PathBuf::from(a);
        if pb.is_file() {
            return Some(pb);
        }
    }

    find_on_path(&[
        "chromium",
        "chromium-browser",
        "google-chrome",
        "google-chrome-stable",
        "brave-browser",
        "microsoft-edge",
        "chrome",
    ])
}

fn find_on_path(names: &[&str]) -> Option<PathBuf> {
    let path = std::env::var_os("PATH")?;
    for dir in std::env::split_paths(&path) {
        for n in names {
            let cand = dir.join(n);
            if cand.is_file() {
                return Some(cand);
            }
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ff_cfg() -> BrowserConfig {
        BrowserConfig {
            bin: PathBuf::from("/opt/firefox/firefox"),
            engine: Engine::Firefox,
            listen: "127.0.0.1:8080".parse().unwrap(),
            spki_b64: String::new(),
            ca_pem: "-----BEGIN CERTIFICATE-----\nMII...\n-----END CERTIFICATE-----\n".into(),
            profile_dir: PathBuf::from("/tmp/shrike-ff"),
            start_url: "about:home".into(),
        }
    }

    fn chromium_cfg() -> BrowserConfig {
        BrowserConfig {
            bin: PathBuf::from("/usr/bin/chromium"),
            engine: Engine::Chromium,
            listen: "127.0.0.1:8080".parse().unwrap(),
            spki_b64: "AAAABBBBCCCCDDDDEEEEFFFFGGGGHHHHIIIIJJJJKKK=".into(),
            ca_pem: String::new(),
            profile_dir: PathBuf::from("/tmp/shrike-profile"),
            start_url: "http://shrike/".into(),
        }
    }

    #[test]
    fn detects_engine_from_binary_name() {
        assert_eq!(
            detect_engine(Path::new("/opt/firefox/firefox")),
            Engine::Firefox
        );
        assert_eq!(
            detect_engine(Path::new("/usr/bin/firefox-esr")),
            Engine::Firefox
        );
        assert_eq!(
            detect_engine(Path::new("/usr/bin/chromium")),
            Engine::Chromium
        );
        assert_eq!(
            detect_engine(Path::new("/usr/bin/google-chrome")),
            Engine::Chromium
        );
    }

    #[test]
    fn firefox_user_js_sets_the_proxy_and_home() {
        let js = firefox_user_js("127.0.0.1:8080".parse().unwrap(), "about:home");
        assert!(js.contains(r#"user_pref("network.proxy.type", 1);"#));
        assert!(js.contains(r#"user_pref("network.proxy.http", "127.0.0.1");"#));
        assert!(js.contains(r#"user_pref("network.proxy.http_port", 8080);"#));
        assert!(js.contains(r#"user_pref("network.proxy.ssl_port", 8080);"#));
        assert!(js.contains(r#"user_pref("browser.startup.homepage", "about:home");"#));
        // Background phone-home is quieted so opening Firefox does not flood history.
        assert!(js.contains(r#"user_pref("browser.safebrowsing.malware.enabled", false);"#));
        assert!(js.contains(r#"user_pref("app.normandy.enabled", false);"#));
        assert!(js.contains(r#"user_pref("extensions.blocklist.enabled", false);"#));
    }

    #[test]
    fn firefox_policies_install_the_ca_and_are_valid_json() {
        let json = firefox_policies_json(Path::new("/tmp/d/shrike-ca.pem"));
        let v: serde_json::Value = serde_json::from_str(&json).expect("valid json");
        assert_eq!(
            v["policies"]["Certificates"]["Install"][0],
            serde_json::Value::String("/tmp/d/shrike-ca.pem".into())
        );
        assert_eq!(
            v["policies"]["DisableTelemetry"],
            serde_json::Value::Bool(true)
        );
    }

    #[test]
    fn firefox_policies_escape_windows_paths() {
        let json = firefox_policies_json(Path::new("C:\\ProgramData\\shrike\\ca.pem"));
        let v: serde_json::Value =
            serde_json::from_str(&json).expect("valid json even with backslashes");
        assert_eq!(
            v["policies"]["Certificates"]["Install"][0],
            serde_json::Value::String("C:\\ProgramData\\shrike\\ca.pem".into())
        );
    }

    #[test]
    fn firefox_args_isolate_and_open_start_url() {
        let a = firefox_args(&ff_cfg());
        assert!(a.iter().any(|s| s == "-no-remote"));
        let i = a
            .iter()
            .position(|s| s == "-profile")
            .expect("profile flag");
        assert_eq!(a[i + 1], "/tmp/shrike-ff");
        assert_eq!(a.last().unwrap(), "about:home");
    }

    #[test]
    fn chromium_args_wire_proxy_ca_and_profile() {
        let a = build_args(&chromium_cfg());
        assert!(
            a.iter()
                .any(|s| s == "--proxy-server=http://127.0.0.1:8080")
        );
        assert!(
            a.iter()
                .any(|s| s == "--ignore-certificate-errors-spki-list=AAAABBBBCCCCDDDDEEEEFFFFGGGGHHHHIIIIJJJJKKK=")
        );
        assert!(a.iter().any(|s| s.starts_with("--user-data-dir=")));
    }
}
